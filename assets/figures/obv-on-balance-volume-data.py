"""OBV 예시용 가정 일봉 데이터(실제 종목 아님). (날, 종가, 거래량)."""
A = [('1일', 10000, 50000), ('2일', 10200, 80000), ('3일', 10100, 30000), ('4일', 10100, 40000),
     ('5일', 10400, 120000), ('6일', 10300, 20000), ('7일', 10500, 90000), ('8일', 10450, 25000)]
# 다이버전스 예시: 고점은 높아지는데 OBV 고점은 낮아짐
B = [('1일', 10000, 50000), ('2일', 10300, 20000), ('3일', 10100, 70000),
     ('4일', 10400, 15000), ('5일', 10200, 60000), ('6일', 10500, 10000)]
def obv(bars, start=0):
    out = [start]
    for (_, p0, _), (_, p1, v) in zip(bars, bars[1:]):
        out.append(out[-1] + (v if p1 > p0 else -v if p1 < p0 else 0))
    return out
if __name__ == '__main__':
    for name, bars in (('A', A), ('B', B)):
        for b, o in zip(bars, obv(bars)): print(name, *b, o)
    print('start=1,000,000', obv(A, 1_000_000))
